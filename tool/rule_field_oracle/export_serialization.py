"""Export Rust test data from the executed rule-field raw serialization golden."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
EVIDENCE = HERE / "evidence/review-host"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


manifest = json.loads((EVIDENCE / "manifest.json").read_text(encoding="utf-8"))
assert manifest["baseline"] == "14dd24945b2914ce2708b8abaa4ee67ceef892af"
assert sha(HERE / "review-fixtures.json") == manifest["fixturesSha256"]
assert sha(EVIDENCE / "golden.json") == manifest["goldenSha256"]
cases = {row["name"]: row for row in json.loads((HERE / "review-fixtures.json").read_text(encoding="utf-8"))}
golden = json.loads((EVIDENCE / "golden.json").read_text(encoding="utf-8"))
rows = []
for name in ["node-raw-double", "node-raw-script-style", "collection-raw-double", "collection-raw-script-style", "collection-raw-empty"]:
    row = cases[name]
    observed = golden[name]
    assert observed["error"] is None and len(observed["values"]) == 1
    units = observed["values"][0]
    assert not any(0xd800 <= unit <= 0xdfff for unit in units)
    expected = "".join(chr(unit) for unit in units)
    # These controlled node rows select the first li; collection rows select
    # every li. Both use the same source and actual fixed-JAR output.
    selector = "li:first-child" if row["type"] == "node" else "li"
    fields = [name, row["content"], selector, expected]
    assert all('"###' not in field for field in fields)
    rows.append("    (" + ", ".join('r###"' + field + '"###' for field in fields) + "),")
text = "// Generated by tool/rule_field_oracle/export_serialization.py.\n// Expected strings are the executed Jsoup 1.16.2 outputs, not hand-written.\nconst SERIALIZATION_ROWS: &[(&str, &str, &str, &str)] = &[\n"
text += "\n".join(rows) + "\n];\n"
target = ROOT / "packages/fjs/liber_html/tests/data/rule_field_serialization.rs"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(text, encoding="utf-8", newline="\n")
print(f"Exported {len(rows)} serialization rows; SHA256 {sha(target)}")
